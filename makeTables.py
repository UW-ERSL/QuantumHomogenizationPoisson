"""makeTables.py -- every table of the paper, written to tables/ as LaTeX.

    python makeTables.py                 all four tables (about 1 minute)
    python makeTables.py inverse         just that one
    python makeTables.py --list          names and destinations

Each file holds only the `tabular`, so the surrounding `table` environment,
the caption and the label stay in main.tex where they can be edited:

    \\begin{table}[H]
    \\caption{...}
    \\label{tab:inverse}
    \\centering
    \\input{tables/inverse}
    \\end{table}

Every claim the text makes about a table is ASSERTED before the table is
written, so a table cannot go stale relative to the code. Scalar conduction,
contrast rho = 10 unless stated; the three test cells are those of cells.py.
The values the text quotes are printed after each table.
"""
from __future__ import annotations

import os
import sys

import numpy as np

import cells
from verify_square import prop4_check
from verify_full_unitary import full_error
from verify_inverse import inverse_case, residual, LOADS

TABDIR = "tables"
RHO = 10.0
EPS = 1e-6


def write(name: str, spec: str, header: list[str], rows: list, footer: list | None = None) -> None:
    """Emit one tabular; `footer` is one row set off by a rule (a total)."""
    os.makedirs(TABDIR, exist_ok=True)
    out = ["% generated by makeTables.py -- do not edit",
           f"\\begin{{tabular}}{{{spec}}}", "\\toprule",
           " & ".join(header) + r"\\", "\\midrule"]
    out += [" & ".join(str(c) for c in r) + r"\\" for r in rows]
    if footer:
        out += ["\\midrule", " & ".join(str(c) for c in footer) + r"\\"]
    out += ["\\bottomrule", "\\end{tabular}", ""]
    open(f"{TABDIR}/{name}.tex", "w").write("\n".join(out))
    print(f"    {TABDIR}/{name}.tex")


def sci(x: float, digits: int = 2) -> str:
    """$a.b \\times 10^{e}$ with `digits` significant digits."""
    e = int(np.floor(np.log10(abs(x))))
    m = round(x / 10 ** e, digits - 1)
    if abs(m) >= 10:
        m, e = m / 10, e + 1
    return f"${m:.{digits - 1}f} \\times 10^{{{e}}}$"


def p10(x: float) -> str:
    """$10^{k}$ for an exact power of ten."""
    k = int(round(np.log10(x)))
    assert abs(x - 10.0 ** k) < 1e-9 * x
    return "$10$" if k == 1 else f"$10^{{{k}}}$"


def intx(x) -> str:
    """Integer with a thin-space thousands separator."""
    return f"${int(x):,}$".replace(",", "{,}")


def kappa_fmt(x: float) -> str:
    return f"${x:.0f}$" if x < 1000 else sci(x, 3)


# ==========================================================================
#  tab:geometry (Sec. 5.1): extreme eigenvalues of Mtilde for the three cells
# ==========================================================================
def tab_geometry(N: int = 256, rhos=(10.0, 1e4)) -> None:
    rows = []
    for g in cells.GEOMETRIES:
        orc = cells.check_oracle(g)               # R_chi reproduces 2 chi - 1, N = 16 ... 256
        for rho in rhos:
            c = cells.Cell(g, N, rho)
            lo, hi = cells.extreme_eigs(c)
            assert abs(1 / lo - rho) < 1e-5 * rho and abs(hi - 1) < 1e-8, (g, rho)   # kappa = rho
            first = rho == rhos[0]
            rows.append([g if first else "", f"${c.vf:.3g}$" if first else "",
                         f"${orc['toffoli']}$" if first else "", p10(rho),
                         f"${lo * rho:.6f}$", f"${hi:.6f}$", f"${1 / lo / rho:.6f}$"])
            print(f"       {g:8s} rho={rho:g} R_chi Toffolis={orc['toffoli']} "
                  f"rho*lambda_min={lo * rho:.10f} lambda_max={hi:.12f}")
    write("geometry", "lrrrrrr", ["geometry", "$v_f$", "$R_\\chi$ Toffoli", "$\\rho$",
                                  "$\\rho\\,\\lambda_{\\min}$", "$\\lambda_{\\max}$",
                                  "$\\kappa(\\tilde{\\mat{M}})/\\rho$"], rows)


# ==========================================================================
#  tab:resources (Sec. 5.5): the inverse at N = 1024
# ==========================================================================
def tab_resources(N: int = 1024, eps_ps=(1e-3, 1e-6)) -> None:
    rows = []
    for e in eps_ps:
        v = cells.inverse_resources("square", N, RHO, e)
        rows.append([p10(e), f"${v['d']}$", f"${v['C']:.1f}$", f"${v['F']}$",
                     intx(v["toffoli_uv"]), intx(v["toffoli_per_query"]), f"${v['rot_per_query']}$",
                     sci(v["toffoli_total"], 2), intx(v["qubits"])])
        print(f"       eps_p={e:g}: d={v['d']} C={v['C']:.3f} F={v['F']} per query={v['toffoli_per_query']:,} "
              f"rotations={v['rot_per_query']} total={v['toffoli_total']:.3e} qubits={v['qubits']:,}")
    v3, v6 = (cells.inverse_resources("square", N, RHO, e) for e in (1e-3, 1e-6))
    assert (v6["d"], v6["F"], v6["toffoli_uv"], v6["toffoli_per_query"], v6["rot_per_query"],
            v6["qubits"]) == (145, 45, 44462, 88926, 588, 5699)               # Secs. 3.8, 5.5
    assert round(v6["toffoli_total"], -5) == 1.29e7                            # "1.3 x 10^7"
    assert (v3["d"], v3["F"], v3["qubits"]) == (77, 34, 3576) and round(v3["toffoli_total"], -5) == 4.0e6
    write("resources", "rrrrrrrrr", ["$\\epsilon_p$", "$d_t$", "$C$", "$F$", "Toffoli/$\\mathcal{U}_V$",
                                     "Toffoli/query", "rotations/query", "Toffoli", "qubits"], rows)


# ==========================================================================
#  tab:be-M: encoding of Mtilde from the gate-level circuit
# ==========================================================================
def tab_be_M() -> None:
    rows = []
    for N in (8, 16):
        for F in (24, 32):
            r = prop4_check(N, RHO, F)
            delta, chk = full_error(int(np.log2(N)), F)
            assert r["clean"] and chk["work_bits_left_set"] == 0
            assert r["err"] < 2 * delta, (N, F, r["err"], delta)    # "below 2 delta"
            assert abs(r["spec_min"] * RHO - 1) < 1e-12 and abs(r["spec_max"] - 1) < 1e-12
            assert abs(r["sbar"] - 0.325) < 1e-12
            rows.append([f"${N}$", f"${F}$", sci(r["err"]), sci(2 * delta)])
    write("be_M", "rrrr", ["$N$", "$F$", "difference", "$2\\delta$"], rows)


# ==========================================================================
#  tab:inverse: the preconditioned inverse on four sources
# ==========================================================================
def tab_inverse() -> None:
    res = residual(RHO, EPS)
    rows, dev = [], {24: 0.0, 32: 0.0}
    for N in (8, 16, 32, 64):
        r = inverse_case(N, RHO, EPS, F_bits=(24, 32) if N <= 16 else ())
        e = r["errs"]
        assert max(e.values()) <= EPS, (N, e)                       # "at most eps_p"
        assert abs(e["worst"] / res - 1) < 1e-3, (N, e["worst"], res)   # "equals the residual"
        for Fb, ec in r["circuit"].items():
            dev[Fb] = max(dev[Fb], max(abs(ec[k] - e[k]) for k in LOADS))
        rows.append([f"${N}$", f"${r['d']}$"] + [sci(e[k]) for k in LOADS])
    assert dev[32] < 1e-8 and dev[24] < 2e-7, dev
    write("inverse", "rrrrrr",
          ["$N$", "$d_t$", "smooth", "random", "cell", "worst"], rows)
    print(f"       residual of q_t = {res:.3e}; circuit deviation F=24: {dev[24]:.1e}, "
          f"F=32: {dev[32]:.1e}")


TABLES = {
    "geometry":  (tab_geometry,  "extreme eigenvalues of Mtilde, three cells (tab:geometry, Sec. 5.1)"),
    "be_M":      (tab_be_M,      "encoding of Mtilde from the gate-level circuit (tab:be-M, Sec. 5.3)"),
    "inverse":   (tab_inverse,   "the inverse on four sources (tab:inverse, Sec. 5.4)"),
    "resources": (tab_resources, "logical resources of the inverse (tab:resources, Sec. 5.5)"),
}


def main(argv) -> None:
    if "--list" in argv:
        for k, (_, d) in TABLES.items():
            print(f"  {k:<10} {d}")
        return
    wanted = [a for a in argv if not a.startswith("-")] or list(TABLES)
    bad = [w for w in wanted if w not in TABLES]
    if bad:
        raise SystemExit(f"unknown table(s) {bad}; choose from {sorted(TABLES)}")
    for name in wanted:
        fn, desc = TABLES[name]
        print(f"{name}  ({desc})")
        fn()
    print("\ndone")


if __name__ == "__main__":
    main(sys.argv[1:])
